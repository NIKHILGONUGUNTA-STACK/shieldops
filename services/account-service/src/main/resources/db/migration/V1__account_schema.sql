CREATE SCHEMA IF NOT EXISTS account_data;
CREATE TABLE account_data.accounts (
  id UUID PRIMARY KEY,
  account_number VARCHAR(34) NOT NULL UNIQUE,
  customer_id UUID NOT NULL,
  currency VARCHAR(3) NOT NULL,
  balance DECIMAL(19,4) NOT NULL CHECK (balance >= 0),
  status VARCHAR(12) NOT NULL CHECK (status IN ('ACTIVE','BLOCKED','CLOSED')),
  opened_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX accounts_customer_id_idx ON account_data.accounts(customer_id);
