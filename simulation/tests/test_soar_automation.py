def test_dynamic_waf_ip_ban_lifecycle():
    exporter = DynamicWafExporter()
    rule = exporter.add_ban("198.51.100.42", "Credential Stuffing", "INC-001", ttl_seconds=3600)

    assert rule["ipOrCidr"] == "198.51.100.42"
    assert exporter.is_banned("198.51.100.42") is True
    assert exporter.is_banned("198.51.100.43") is False

    # Remove ban
    removed = exporter.remove_ban(rule["id"])
    assert removed is True
    assert exporter.is_banned("198.51.100.42") is False


def test_dynamic_waf_subnet_ban():
    exporter = DynamicWafExporter()
    exporter.add_ban("203.0.113.0/24", "BOLA Exfiltration Campaign", "INC-002", ttl_seconds=3600)

    assert exporter.is_banned("203.0.113.10") is True
    assert exporter.is_banned("203.0.113.254") is True
    assert exporter.is_banned("203.0.114.1") is False


def test_dynamic_waf_export_schemas():
    exporter = DynamicWafExporter()
    exporter.add_ban("198.51.100.10", "DDoS Mitigation", "INC-100", ttl_seconds=3600)
    exporter.add_ban("192.0.2.0/24", "Botnet Probe", "INC-101", ttl_seconds=3600)

    # Cloudflare Schema
    cf = exporter.to_cloudflare_payload()
    assert cf["kind"] == "ip"
    assert len(cf["items"]) == 2
    assert cf["items"][0]["ip"] == "198.51.100.10"
    assert "INC-100" in cf["items"][0]["comment"]

    # AWS WAF Schema
    aws = exporter.to_aws_waf_ipset()
    assert aws["IPSet"]["Scope"] == "REGIONAL"
    assert "198.51.100.10/32" in aws["IPSet"]["Addresses"]
    assert "192.0.2.0/24" in aws["IPSet"]["Addresses"]

    # iptables Schema
    ipt = exporter.to_iptables_rules()
    assert len(ipt) == 2
    assert "iptables -I INPUT -s 198.51.100.10" in ipt[0]
    assert "-j DROP" in ipt[0]


def test_token_revocation_jti_and_subject_cutoff():
    ledger = TokenRevocationLedger()
    t0 = time.time()

    # Normal clean token
    assert ledger.is_revoked("clean-jti", "user1", t0) is False

    # Revoke specific JTI
    ledger.revoke_token("bad-jti-1", "user1", "Exfiltrated device", ttl_seconds=3600)
    assert ledger.is_revoked("bad-jti-1", "user1", t0) is True
    assert ledger.is_revoked("clean-jti-2", "user1", t0) is False

    # Subject cutoff revocation (e.g. password reset / account takeover)
    cutoff_time = time.time()
    ledger.revoke_subject("user2", "Password reset")

    # Tokens issued before cutoff are revoked
    assert ledger.is_revoked("old-jti", "user2", cutoff_time - 10) is True
    # Fresh token issued after cutoff is valid
    assert ledger.is_revoked("fresh-jti", "user2", cutoff_time + 10) is False


def test_adaptive_challenge_state_transitions():
    engine = AdaptiveChallengeEngine()

    # Risk evaluation
    assert engine.evaluate_threat(0.45) == "ALLOW"
    assert engine.evaluate_threat(0.78) == "STEP_UP_CHALLENGE"
    assert engine.evaluate_threat(0.95) == "BLOCK_AND_BAN"

    # Issue challenge for ambiguous risk
    session = engine.issue_challenge("sess-abc", "Elevated BOLA risk", threat_risk=0.82)
    nonce = session["challengeNonce"]
    assert nonce.startswith("CHAL-")
    assert engine.is_cleared("sess-abc") is False

    # Failed challenge
    assert engine.verify_challenge("sess-abc", "WRONG-NONCE") is False
    assert engine.is_cleared("sess-abc") is False

    # Successful challenge
    assert engine.verify_challenge("sess-abc", nonce) is True
    assert engine.is_cleared("sess-abc") is True
