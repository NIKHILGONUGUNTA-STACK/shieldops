import time
import uuid
from datetime import datetime, timezone, timedelta
from typing import Dict, List, Any


class DynamicWafExporter:
    """Python reference implementation of the Gateway Dynamic WAF exporter for testing/simulation."""

    def __init__(self):
        self.rules: Dict[str, Dict[str, Any]] = {}

    def add_ban(self, ip_or_cidr: str, reason: str, incident_id: str, ttl_seconds: int = 86400, source: str = "SOAR"):
        ban_id = str(uuid.uuid4())
        now = time.time()
        self.rules[ban_id] = {
            "id": ban_id,
            "ipOrCidr": ip_or_cidr,
            "reason": reason,
            "incidentId": incident_id,
            "createdAt": now,
            "expiresAt": now + ttl_seconds,
            "source": source
        }
        return self.rules[ban_id]

    def remove_ban(self, ban_id: str) -> bool:
        return self.rules.pop(ban_id, None) is not None

    def get_active_bans(self) -> List[Dict[str, Any]]:
        now = time.time()
        return [r for r in self.rules.values() if r["expiresAt"] > now]

    def is_banned(self, ip: str) -> bool:
        active = self.get_active_bans()
        for r in active:
            target = r["ipOrCidr"]
            if "/" in target:
                # Basic subnet check (e.g. 192.168.1.0/24)
                prefix = target.split("/")[0]
                prefix_parts = prefix.split(".")[:3]
                if ip.split(".")[:3] == prefix_parts:
                    return True
            else:
                if ip == target:
                    return True
        return False

    def to_cloudflare_payload(self) -> Dict[str, Any]:
        active = self.get_active_bans()
        return {
            "name": "Aegis Dynamic Blocklist",
            "description": "Auto-generated IP ban list by Aegis Autonomous SOAR",
            "kind": "ip",
            "items": [{"ip": r["ipOrCidr"], "comment": f"SOAR:{r['incidentId']}:{r['reason']}"} for r in active]
        }

    def to_aws_waf_ipset(self) -> Dict[str, Any]:
        active = self.get_active_bans()
        addresses = []
        for r in active:
            cidr = r["ipOrCidr"]
            if "/" not in cidr:
                cidr = f"{cidr}/32"
            addresses.append(cidr)
        return {
            "IPSet": {
                "Name": "Aegis-Autonomous-Blocklist",
                "Scope": "REGIONAL",
                "IPAddressVersion": "IPV4",
                "Description": "Dynamic IP blocklist generated by Aegis SOAR",
                "Addresses": addresses
            }
        }

    def to_iptables_rules(self) -> List[str]:
        active = self.get_active_bans()
        commands = []
        for r in active:
            commands.append(f"iptables -I INPUT -s {r['ipOrCidr']} -m comment --comment 'AEGIS_SOAR_{r['incidentId']}' -j DROP")
        return commands


class TokenRevocationLedger:
    """Python reference implementation of the Gateway Token Revocation Ledger for testing/simulation."""

    def __init__(self):
        self.revoked_tokens: Dict[str, Dict[str, Any]] = {}
        self.subject_cutoffs: Dict[str, float] = {}

    def revoke_token(self, jti: str, subject: str, reason: str, ttl_seconds: int = 86400):
        now = time.time()
        self.revoked_tokens[jti] = {
            "jti": jti,
            "subject": subject,
            "reason": reason,
            "revokedAt": now,
            "expiresAt": now + ttl_seconds
        }

    def revoke_subject(self, subject: str, reason: str):
        self.subject_cutoffs[subject] = time.time()

    def is_revoked(self, jti: str, subject: str, issued_at: float) -> bool:
        now = time.time()
        if jti in self.revoked_tokens:
            record = self.revoked_tokens[jti]
            if record["expiresAt"] > now:
                return True
            else:
                del self.revoked_tokens[jti]

        if subject in self.subject_cutoffs:
            cutoff = self.subject_cutoffs[subject]
            if issued_at < cutoff:
                return True

        return False


class AdaptiveChallengeEngine:
    """Python reference implementation of the Adaptive Step-Up Challenge Gate."""

    def __init__(self):
        self.sessions: Dict[str, Dict[str, Any]] = {}

    def evaluate_threat(self, risk_score: float) -> str:
        """Categorizes behavioral threat risk into mitigation actions."""
        if risk_score >= 0.90:
            return "BLOCK_AND_BAN"
        elif risk_score >= 0.70:
            return "STEP_UP_CHALLENGE"
        else:
            return "ALLOW"

    def issue_challenge(self, session_id: str, reason: str, threat_risk: float) -> Dict[str, Any]:
        now = time.time()
        nonce = f"CHAL-{uuid.uuid4().hex[:8].upper()}"
        session = {
            "sessionId": session_id,
            "challengeNonce": nonce,
            "reason": reason,
            "threatRisk": threat_risk,
            "issuedAt": now,
            "expiresAt": now + 300,  # 5 min
            "verified": False,
            "clearanceExpiresAt": None
        }
        self.sessions[session_id] = session
        return session

    def verify_challenge(self, session_id: str, response_token: str) -> bool:
        session = self.sessions.get(session_id)
        if not session:
            return False
        now = time.time()
        if now > session["expiresAt"]:
            return False
        if session["challengeNonce"] == response_token:
            session["verified"] = True
            session["clearanceExpiresAt"] = now + 900  # 15 min clearance
            return True
        return False

    def is_cleared(self, session_id: str) -> bool:
        session = self.sessions.get(session_id)
        if not session or not session["verified"]:
            return False
        return time.time() < session["clearanceExpiresAt"]


